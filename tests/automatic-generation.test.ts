const silhouette=[[0,4.8],[4.2,0],[7.5,2.3],[5.3,4.2],[6.85,7.3],[2.2,7.3]].map(([x,y])=>({x,y}))
const T=2e-5,distance=(a:Point,b:Point)=>Math.hypot(a.x-b.x,a.y-b.y)
function pointDistance(q:Point,a:Point,b:Point){const x=b.x-a.x,y=b.y-a.y,l=x*x+y*y,t=l?Math.max(0,Math.min(1,((q.x-a.x)*x+(q.y-a.y)*y)/l)):0;return Math.hypot(q.x-a.x-x*t,q.y-a.y-y*t)}
function generatedSettings(degrees:number):Settings{
  const angle=degrees*Math.PI/180
  return {...DEFAULT_SETTINGS,polygon:silhouette.map(q=>({x:q.x*Math.cos(angle)-q.y*Math.sin(angle),y:q.x*Math.sin(angle)+q.y*Math.cos(angle)})),frameSelection:'manual',pedestalSelection:'manual',height:261,variation:0,pedestalDiameter:205,pedestalClearance:120,frameStock:3,joints:'butt',perimeterJoints:true}
}
function automaticAudit(plan:Plan,s:Settings){
  const frame=plan.frame,diameter=(s.pedestalDiameter??150)/1000,clearance=diameter/2+(s.pedestalClearance??0)/1000
  assert.equal(frame.manual,false,'This must be generated by the normal planner, with no editor layout')
  assert.equal(frame.geometryPass,true,frame.issues.join('; '));assert.ok(frame.members.length&&frame.pedestals.length)
  for(const [i,q] of frame.pedestals.entries()){
    for(const other of frame.pedestals.slice(0,i))assert.ok(distance(q,other)>=diameter-T,'Automatically generated circular bases overlap')
    for(const ring of [plan.p,...plan.holes])for(let j=0;j<ring.length;j++)assert.ok(pointDistance(q,ring[j],ring[(j+1)%ring.length])>=clearance-T,'Generation reduced the actual base/edge clearance')
    assert.ok(frame.members.some(m=>m.kind===(frame.rule.bearer?'bearer':'joist')&&m.support!=='transfer'&&pointDistance(q,m.a,m.b)<T),'A generated pedestal is not on its actual primary member')
  }
  for(const m of frame.members){
    assert.ok(distance(m.a,m.b)<=s.frameStock+T,'A generated member exceeds available stock')
    if(m.kind!==(frame.rule.bearer?'bearer':'joist')||m.support==='transfer'||m.role==='bearer-link')continue
    const positions=frame.pedestals.filter(q=>pointDistance(q,m.a,m.b)<T).map(q=>distance(m.a,q)).sort((a,b)=>a-b)
    assert.ok(positions.length,'A generated primary segment has no actual bearing')
    for(let i=1;i<positions.length;i++)assert.ok(positions[i]-positions[i-1]<=frame.rule.support+T,'Generation exceeded the report span')
  }
  assert.ok(frame.maxPrimarySpan<=frame.rule.support+T);assert.ok(!frame.rule.bearer||frame.maxSecondarySpan<=frame.rule.bearerSpacing+T)
  assert.ok(frame.boardChecks.every(c=>c.ok));assert.ok(frame.checks.every(c=>c.ok))
  assert.equal(installerPlan(plan,s).construction.manual,false)
  assert.equal(buildCsvReport('pedestals',plan,s,{}).rows.length,frame.pedestals.length)
}
for(const degrees of [0,11,23,45,67])for(const frame of ['small','big','small-small','big-small'] as const)for(const direction of ['horizontal','vertical'] as const)for(const load of [3,5] as const){
  test(`normal generation needs no editing: ${degrees}°/${frame}/${direction}/${load} kN`,()=>{
    const s={...generatedSettings(degrees),frame,direction,load},before=JSON.stringify(s)
    assert.equal(s.supportLayout,undefined);automaticAudit(planDeck(s),s)
    assert.equal(JSON.stringify(s),before,'Generation must retain the customer dimensions, frame, base, clearance and stock inputs')
  })
}
for(const objective of ['cost','simple','pedestals','spread'] as const)for(const degrees of [0,23,45,67])test(`normal automatic frame/product selection completes ${degrees}°/${objective}`,()=>{
  const input={...generatedSettings(degrees),load:5 as const,frameSelection:'auto' as const,pedestalSelection:'auto' as const,selectionObjective:objective},result=computeDeckPlanning(input,{})
  assert.equal(result.error,'');assert.ok(result.plan)
  automaticAudit(result.plan,result.settings)
  assert.equal(result.settings.supportLayout,undefined);assert.equal(result.settings.height,input.height);assert.equal(result.settings.load,input.load);assert.equal(result.settings.frameStock,input.frameStock);assert.equal(result.settings.pedestalClearance,input.pedestalClearance)
  assert.ok(result.recommendation!.options.every(option=>option.choice),'The generator must also produce all four viable frame options')
})
for(const frame of ['small-small','big-small'] as const)for(const direction of ['horizontal','vertical'] as const)for(const load of [3,5] as const)test(`L-shaped arms get usable automatic bearer rows: ${frame}/${direction}/${load}`,()=>{
  const s={...generatedSettings(0),polygon:[[0,0],[6,0],[6,1.3],[3,1.3],[3,4],[0,4]].map(([x,y])=>({x,y})),frame,direction,load}
  automaticAudit(planDeck(s),s)
})
test('the actual generation worker returns a complete automatic layout without a support-editor payload',async()=>{
  const settings={...generatedSettings(45),load:5 as const,frameSelection:'auto' as const,pedestalSelection:'auto' as const},source=new URL('../src/planning.worker.ts',import.meta.url).href
  const bridge=`const {parentPort}=require('node:worker_threads');globalThis.self={onmessage:null,postMessage:data=>parentPort.postMessage(data)};parentPort.on('message',data=>self.onmessage({data}));import(${JSON.stringify(source)}).then(()=>parentPort.postMessage({ready:true}));`,worker=new Worker(bridge,{eval:true,execArgv:['--experimental-strip-types']})
  try{
    const reply=await new Promise<PlanningReply>((resolve,reject)=>{worker.on('error',reject);worker.on('message',data=>data.ready?worker.postMessage({key:'automatic-generation',settings,prices:{}}):resolve(data))})
    assert.equal(reply.result.error,'');assert.equal(reply.result.settings.supportLayout,undefined);assert.ok(reply.result.plan)
    automaticAudit(reply.result.plan,reply.result.settings)
    const synchronous=computeDeckPlanning(settings,{})
    assert.deepEqual(reply.result.plan.frame.members,synchronous.plan!.frame.members);assert.deepEqual(reply.result.plan.frame.pedestals,synchronous.plan!.frame.pedestals)
  }finally{await worker.terminate()}
})
